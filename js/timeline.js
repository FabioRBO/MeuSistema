window.addEventListener('DOMContentLoaded', function() {
    const timelineEmbed = document.getElementById('timeline-embed');
    let idSlideAtual = null;

    window.timeline = new TL.Timeline('timeline-embed', timelineData, {
        language: 'pt-br',
        initial_zoom: 1,
        scale_factor: 2
    });

    function obterSlideAtual() {
        const id = idSlideAtual || window.timeline.current_id;

        return id
            ? document.getElementById(id)
            : null;
    }

    function obterMidiaAtual() {
        const slideAtual = obterSlideAtual();

        return slideAtual
            ? slideAtual.querySelector('.tl-media')
            : null;
    }

    function prepararMidias() {
        timelineEmbed.querySelectorAll('.tl-media').forEach(function(media) {
            if (media.dataset.toggleConfigurado === 'true') return;

            media.dataset.toggleConfigurado = 'true';
            media.classList.add('midia_oculta');
        });
    }

    function atualizarBotaoMidia() {
        const botao = document.getElementById('btn-toggle-midia');
        if (!botao) return;

        const media = obterMidiaAtual();

        if (!media) {
            botao.disabled = true;
            botao.innerHTML = 'Sem mídia';
            botao.title = 'Este acontecimento não possui mídia';
            botao.classList.remove('midia_visivel');
            return;
        }

        const ocultada = media.classList.contains('midia_oculta');

        botao.disabled = false;
        botao.innerHTML = ocultada
            ? 'Mídia'
            : 'Ocultar mídia';

        botao.title = ocultada
            ? 'Mostrar mídia'
            : 'Ocultar mídia';

        botao.classList.toggle('midia_visivel', !ocultada);
    }

    function atualizarSlideAtual(uniqueId) {
        if (uniqueId) {
            idSlideAtual = uniqueId;
        }

        prepararMidias();

        setTimeout(function() {
            prepararMidias();
            atualizarBotaoMidia();
        }, 50);
    }

    window.timeline.on('loaded', function() {
        atualizarSlideAtual(window.timeline.current_id);
    });

    window.timeline.on('change', function(dados) {
        atualizarSlideAtual(dados.unique_id);
    });

    document.addEventListener('click', function(event) {
        const botao = event.target.closest('#btn-toggle-midia');
        if (!botao) return;

        event.preventDefault();
        event.stopPropagation();

        const media = obterMidiaAtual();
        if (!media) return;

        const ocultou = media.classList.toggle('midia_oculta');

        if (ocultou) {
            media.querySelectorAll('video, audio').forEach(function(elemento) {
                elemento.pause();
            });
        }

        atualizarBotaoMidia();
    });

    const observadorTimeline = new MutationObserver(function() {
        prepararMidias();
    });

    observadorTimeline.observe(timelineEmbed, {
        childList: true,
        subtree: true
    });

    setTimeout(function() {
        atualizarSlideAtual(window.timeline.current_id);
    }, 700);
});